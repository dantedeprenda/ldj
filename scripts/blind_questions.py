"""Generate a label-blind question set for T1: written from the task description
alone, never from data. Committed with the prompt verbatim BEFORE it is run.

    uv run python scripts/blind_questions.py

One call to the routing paper's generator model (Claude Sonnet 5, here via OpenRouter), temperature
0. The raw reply, requested and returned model ids and usage are saved next to the parsed set.
Format rules (fixed now): exactly 13 questions, each ends with "?", at most 50 words, and no names
of datasets, surveys or annotation schemes. A set that fails is regenerated once; an existing set
is never overwritten. Writes configs/questions/t1_blind.yaml and t1_blind_raw.json.
"""

from __future__ import annotations

import json
import re
from datetime import UTC, datetime
from pathlib import Path

import yaml

from ldj.cache import CallCache
from ldj.cli import load_dotenv
from ldj.llm import ChatBackend

OUT = Path("configs/questions")
MODEL = "anthropic/claude-sonnet-5"
PROMPT = (
    "A content-moderation system must decide whether a social-media comment is hate speech: a "
    "comment that attacks or demeans a group, or a person because they belong to a group, defined "
    "by race, ethnicity, religion, gender, sexual orientation, gender identity, disability or "
    "national origin. It sees only the comment text.\n\n"
    "Write exactly 13 yes/no questions about a comment that a careful reader could answer from the "
    "comment text alone, and whose answers would help decide whether the comment is hate speech. "
    "Do not mention any dataset, survey or annotation scheme. Return a JSON object mapping a short "
    "snake_case id to each question."
)
CONTEXT = (
    "Below is a social-media comment. Answer questions about the comment itself, not about any "
    "post it may be replying to."
)  # the same context line as t1_v1, so only the questions differ
BANNED = re.compile(
    r"measuring hate speech|\bsurvey\b|\brasch\b|\bannotat|\bdataset\b", re.IGNORECASE
)


def parse(text: str) -> dict[str, str]:
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError("no JSON object in reply")
    return {str(k): str(v) for k, v in json.loads(match.group(0)).items()}


def problems(q: dict[str, str]) -> list[str]:
    out = [] if len(q) == 13 else [f"{len(q)} questions, not 13"]
    for k, v in q.items():
        if not v.rstrip().endswith("?"):
            out.append(f"{k}: not a question")
        if len(v.split()) > 50:
            out.append(f"{k}: over 50 words")
        if BANNED.search(v):
            out.append(f"{k}: names a dataset, survey or annotation scheme")
    return out


def main() -> int:
    target = OUT / "t1_blind.yaml"
    if target.exists():
        print(f"{target} exists; never overwritten")
        return 0
    load_dotenv()
    backend = ChatBackend(MODEL, cache=CallCache(".cache/calls.sqlite"), max_usd=1.0)
    records = []
    for attempt in (1, 2):
        # the attempt number is appended outside the prompt text only to bypass the cache on retry
        system = "" if attempt == 1 else " "
        reply, _latency, cost = backend.complete(system, PROMPT)
        rec = {
            "attempt": attempt,
            "created": datetime.now(UTC).isoformat(timespec="seconds"),
            "requested_model": MODEL,
            "prompt": PROMPT,
            "reply": reply,
            "cost_usd": cost,
        }
        records.append(rec)
        try:
            q = parse(reply)
            issues = problems(q)
        except ValueError as e:
            q, issues = {}, [str(e)]
        rec["problems"] = issues
        if not issues:
            break
    (OUT / "t1_blind_raw.json").write_text(json.dumps(records, indent=1))
    if issues:
        print("both attempts failed the format check:", issues)
        return 1
    header = (
        "# T1 label-blind question set. Generated by scripts/blind_questions.py from the task\n"
        "# description only (prompt committed before the run); raw reply in t1_blind_raw.json.\n"
    )
    target.write_text(
        header + yaml.safe_dump({"context": CONTEXT, "questions": q}, sort_keys=False, width=100)
    )
    print(f"wrote {target}: {len(q)} questions, attempt {attempt}, ${backend.new_spend:.4f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
